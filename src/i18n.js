  // Browser language, reduced to one we ship ("fr-CA" -> "fr"); anything else is English.
  function browserLang() {
    const l = String(navigator.language || 'en').slice(0, 2).toLowerCase();
    return S[l] ? l : 'en';
  }

  let choice = 'auto';           // 'auto' or a LANGS key, as picked in About
  let lang = browserLang();      // resolved language

  function setLang(c) {
    choice = S[c] ? c : 'auto';
    lang = choice === 'auto' ? browserLang() : choice;
  }

  function t(key, vars) {
    let s = S[lang][key] ?? S.en[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
    return s;
  }

  const api = { LANGS, t, setLang, lang: () => lang, choice: () => choice, browserLang, strings: S };
  if (typeof module !== 'undefined') module.exports = api;
  else (root.CPF = root.CPF || {}).i18n = api;
